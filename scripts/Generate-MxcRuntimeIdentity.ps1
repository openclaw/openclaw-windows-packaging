#Requires -Version 7.0
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$OutputPath,
    [Parameter(Mandatory)][string]$SdkPackageDirectory
)

$ErrorActionPreference = 'Stop'
$lock = Get-Content -LiteralPath (Join-Path (Split-Path $PSScriptRoot -Parent) 'mxc-runtime.lock.json') -Raw | ConvertFrom-Json
$assembly = Join-Path $SdkPackageDirectory $lock.managedAssembly.path
if (
    !(Test-Path -LiteralPath $assembly -PathType Leaf) -or
    (Get-Item -LiteralPath $assembly).Length -ne $lock.managedAssembly.length -or
    (Get-FileHash -LiteralPath $assembly -Algorithm SHA256).Hash -ine $lock.managedAssembly.sha256
) {
    throw 'The restored MXC managed assembly does not match the pinned NuGet archive.'
}
$cases = foreach ($architecture in @('x64', 'arm64')) {
    $file = @($lock.architectures.$architecture.files | Where-Object stagedPath -eq 'mxc_ffi.dll')
    if ($file.Count -ne 1 -or $file[0].sha256 -notmatch '^[0-9a-f]{64}$' -or $file[0].length -le 0) {
        throw "Missing valid MXC native identity for $architecture."
    }
    "            `"$architecture`" => ($($file[0].length)L, `"$($file[0].sha256)`"),"
}
$source = @"
// <auto-generated />
namespace OpenClaw.Launcher.Mxc;
internal static class MxcRuntimeIdentity
{
    internal static (long Length, string Sha256) ForArchitecture(string architecture) =>
        architecture switch
        {
$($cases -join "`n")
            _ => throw new System.PlatformNotSupportedException("Unsupported MXC architecture.")
        };
}
"@
$source = $source.Replace("`r`n", "`n")
[IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName([IO.Path]::GetFullPath($OutputPath))) | Out-Null
if (!(Test-Path -LiteralPath $OutputPath) -or [IO.File]::ReadAllText($OutputPath) -cne $source) {
    [IO.File]::WriteAllText($OutputPath, $source, [Text.UTF8Encoding]::new($false))
}
